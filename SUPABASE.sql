-- MOONLIGHT ARMY · Árbol de los deseos
-- Ejecuta este SQL en Supabase > SQL Editor > New query.
create table if not exists public.wishes (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 35),
  wish text not null check (char_length(wish) between 1 and 240),
  created_at timestamptz not null default now()
);

alter table public.wishes enable row level security;

-- Cualquier visitante puede leer los deseos compartidos.
create policy "Todos pueden leer los deseos"
on public.wishes for select
to anon, authenticated
using (true);

-- Cualquier visitante puede publicar un deseo.
create policy "Todos pueden agregar deseos"
on public.wishes for insert
to anon, authenticated
with check (
  char_length(trim(name)) between 1 and 35
  and char_length(trim(wish)) between 1 and 240
);

